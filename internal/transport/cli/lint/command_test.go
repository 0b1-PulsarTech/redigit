func TestRunReportsTheMeasures(t *testing.T) {
	t.Parallel()

	big := strings.Repeat("x\n", 901)
	small := strings.Repeat("x\n", 10)
	mockHeader := "// Code generated by MockGen. DO NOT EDIT.\n\npackage x\n"

	testCases := []struct {
		name         string
		path         string
		content      string
		extra        []string
		noBlobs      bool
		wantMeasures string
		wantErr      error
	}{
		{
			name: "red: a big source row", path: "a.go", content: big,
			wantMeasures: "source_added_over,rows_over",
		},
		{name: "green: a small source row", path: "a.go", content: small},
		{
			name: "a big non-go file is not source", path: "notes.md", content: big,
			wantMeasures: "rows_over",
		},
		{
			name: "findings do not change the exit code", path: "a.go", content: big,
			wantMeasures: "source_added_over,rows_over",
		},
		{
			name: "fail-over turns findings into a failure", path: "a.go", content: big,
			extra:        []string{"--fail-over"},
			wantMeasures: "source_added_over,rows_over", wantErr: ErrFailed,
		},
		{
			name: "fail-over passes a clean history", path: "a.go", content: small,
			extra: []string{"--fail-over"},
		},
		{
			name: "without a blob dir no line measure runs and the exit is 0",
			path: "a.go", content: big, noBlobs: true,
		},
		{
			name: "fail-over refuses a run that measured nothing", path: "a.go", content: big,
			extra: []string{"--fail-over"}, noBlobs: true, wantErr: ErrNotMeasured,
		},
		{
			name: "a MockGen file with its marker is not source", path: "x_mock_test.go",
			content:      mockHeader + big,
			wantMeasures: "rows_over",
		},
		{
			name: "a mock-named file without a marker is source", path: "x_mock_test.go",
			content:      "package x\n" + big,
			wantMeasures: "source_added_over,rows_over",
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			dir := ""
			if !testCase.noBlobs {
				dir = blobDirWith(t, map[string]string{"h": testCase.content})
			}

			got, summary, err := runLint(
				t, manifestLine(testCase.path, "h"), dir, testCase.extra...,
			)
			if !errors.Is(err, testCase.wantErr) {
				t.Fatalf("Run() err = %v, want %v", err, testCase.wantErr)
			}

			if strings.Join(got, ",") != testCase.wantMeasures || !summary.Summary ||
				summary.Measured == testCase.noBlobs || summary.Findings != len(got) ||
				len(summary.Deferred) != 5 {
				t.Fatalf("findings = %v, summary = %+v", got, summary)
			}
		})
	}
}

func TestRunMeasuresOnlyWhatItRead(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name     string
		manifest string
		blobDir  string
		extra    []string
		wantErr  error
	}{
		{
			name:     "a blob-less row under a missing blob dir measured nothing",
			manifest: `{"position":0,"subject":"s","blobs":[]}` + "\n",
			blobDir:  "/nonexistent",
		},
		{
			name:     "fail-over refuses a blob-less row",
			manifest: `{"position":0,"subject":"s","blobs":[]}` + "\n",
			blobDir:  "/nonexistent",
			extra:    []string{"--fail-over"},
			wantErr:  ErrNotMeasured,
		},
		{
			name:     "a submodule-only row reads no blob",
			manifest: `{"position":0,"subject":"s","blobs":[{"path":"m","mode":"160000","handle":"h"}]}` + "\n",
			blobDir:  "/nonexistent",
			extra:    []string{"--fail-over"},
			wantErr:  ErrNotMeasured,
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			_, summary, err := runLint(t, testCase.manifest, testCase.blobDir, testCase.extra...)
			if !errors.Is(err, testCase.wantErr) {
				t.Fatalf("Run() err = %v, want %v", err, testCase.wantErr)
			}

			if !summary.Summary || summary.Rows != 1 || summary.Measured || summary.Note == "" ||
				len(summary.Measures) != 0 {
				t.Fatalf("summary = %+v", summary)
			}
		})
	}
}

func TestRunRefusesWhatItCannotRun(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name      string
		args      []string
		wantUsage bool
	}{
		{name: "no arguments", args: nil, wantUsage: true},
		{name: "an unknown flag", args: []string{"--repo", "."}, wantUsage: true},
		{
			name: "a positional argument", args: []string{"--manifest", "m", "extra"},
			wantUsage: true,
		},
		{
			name: "a missing manifest file",
			args: []string{"--manifest", "/nonexistent/m.jsonl"},
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			var stdout bytes.Buffer

			err := Run(context.Background(), testCase.args, &stdout)
			if err == nil || errors.Is(err, write.ErrUsage) != testCase.wantUsage ||
				stdout.Len() != 0 {
				t.Fatalf("Run() err = %v, stdout = %q", err, stdout.String())
			}
		})
	}
}

func TestRunRefusesAMalformedManifestAnEmptyOneAndAMissingBlob(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name     string
		manifest string
		extra    []string
		wantText string
	}{
		{name: "a broken row", manifest: "{nope", wantText: "decode row"},
		{
			name:     "a blob that is not in the dir",
			manifest: `{"position":0,"subject":"s","blobs":[{"path":"a.go","mode":"100644","handle":"absent"}]}` + "\n",
			wantText: "read blob",
		},
		{name: "an empty manifest", manifest: "", wantText: "the manifest holds no row"},
		{
			name: "an empty manifest under fail-over", manifest: "",
			extra: []string{"--fail-over"}, wantText: "the manifest holds no row",
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			var stdout bytes.Buffer

			args := append(
				[]string{
					"--manifest", manifestFile(t, testCase.manifest), "--blob-dir", t.TempDir(),
				},
				testCase.extra...)

			err := Run(context.Background(), args, &stdout)
			if err == nil || stdout.Len() != 0 ||
				!strings.Contains(err.Error(), testCase.wantText) {
				t.Fatalf("Run() err = %v, stdout = %q", err, stdout.String())
			}

			if testCase.manifest == "" && !errors.Is(err, rewriting.ErrManifest) {
				t.Fatalf("Run() err = %v, want rewriting.ErrManifest", err)
			}
		})
	}
}

func TestRunReadsItsLimitsFromTheConfig(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name         string
		config       string
		wantFindings int
		wantErr      bool
	}{
		{name: "defaults leave ten lines alone", config: `{}`},
		{
			name:         "a lowered limit turns ten lines red",
			config:       `{"lint":{"sourceAdded":5,"rowAdded":5}}`,
			wantFindings: 2,
		},
		{name: "an unknown lint setting is refused", config: `{"lint":{"nope":5}}`, wantErr: true},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			dir := blobDirWith(t, map[string]string{"h": strings.Repeat("x\n", 10)})
			configPath := filepath.Join(t.TempDir(), "redigit.json")

			if err := os.WriteFile(configPath, []byte(testCase.config), 0o600); err != nil {
				t.Fatalf("WriteFile() err = %v", err)
			}

			var stdout bytes.Buffer

			err := Run(context.Background(), []string{
				"--manifest", manifestFile(t, manifestLine("a.go", "h")),
				"--blob-dir", dir, "--config", configPath,
			}, &stdout)
			if (err != nil) != testCase.wantErr {
				t.Fatalf("Run() err = %v", err)
			}

			if got := strings.Count(stdout.String(), `"measure"`); got != testCase.wantFindings {
				t.Fatalf(
					"findings = %d, want %d in %q", got, testCase.wantFindings, stdout.String(),
				)
			}
		})
	}
}
