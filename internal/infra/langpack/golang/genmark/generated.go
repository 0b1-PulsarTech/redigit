package genmark

import (
	"bytes"
	"regexp"
)

var generatedMarker = regexp.MustCompile(`(?m)^// Code generated .* DO NOT EDIT\.$`)

func IsGenerated(source []byte) bool {
	// Detect by the marker line, not a _mock_test.go name: hand-written mocks share that suffix.
	return generatedMarker.Match(source)
}

func IsSqlcOutput(source []byte) bool {
	return IsGenerated(source) && bytes.Contains(source, []byte("// Code generated by sqlc."))
}
