// mockgenRule links a generated mock to the interface it structurally
// mirrors. The only record of that link is a "// Source:" header comment, in
// one of three formats: a bare filename in the mock's own directory, an
// import path carrying "(interfaces: A,B,C)", or a relative path that climbs
// out of the directory with "..". The mirrored interface name is recovered
// from the mock's own identifiers: a NewMock/Mock prefix and a MockRecorder
// suffix are mockgen's own naming convention, not ours.
type mockgenRule struct{}

func (mockgenRule) Name() string { return "mockgen" }

func (r mockgenRule) Edges(
	_ context.Context,
	snap entities.Snapshot,
	decls []entities.Decl,
) ([]entities.Edge, error) {
	byFile := groupByFile(decls)

	var edges []entities.Edge

	for file, mockDecls := range byFile {
		source, err := readSource(snap, file)
		if err != nil {
			return nil, err
		}

		sourceLine, ok := mockgenSourceLine(source)
		if !ok {
			continue
		}

		target, err := resolveMockSource(snap, filepath.Dir(file), sourceLine)
		if err != nil {
			return nil, err
		}

		if target == (mockTarget{}) {
			continue
		}

		candidates := mockCandidates(byFile, target)

		for _, dependent := range mockDependents(mockDecls, source) {
			for _, name := range dependent.subjects {
				if provider, found := findTypeNamed(candidates, name); found {
					edges = append(edges, entities.Edge{
						Dependent: dependent.key,
						Provider:  provider,
						Reason:    entities.ReasonMirrors,
					})
				}
			}
		}
	}

	return edges, nil
}

// mockgenSourceLine reports the "// Source: ..." header line mockgen writes,
// only present in a file whose header names MockGen as the generator.
func mockgenSourceLine(source []byte) (string, bool) {
	if !bytes.Contains(source, []byte("Code generated by MockGen")) {
		return "", false
	}

	scanner := bufio.NewScanner(bytes.NewReader(source))
	for scanner.Scan() {
		line := strings.TrimSpace(strings.TrimPrefix(scanner.Text(), "//"))
		if rest, ok := strings.CutPrefix(line, "Source:"); ok {
			return strings.TrimSpace(rest), true
		}
	}

	return "", false
}

// mockTarget is where a mock's source interfaces live: a specific file, or
// (for the import-path header, which names a package rather than a file) a
// directory to search.
type mockTarget struct {
	file string
	dir  string
}

// resolveMockSource classifies the three header formats mockgen writes and
// resolves each to a repo-relative location:
//   - "(interfaces: ...)" - an import path; trimmed against the module path
//     read from the target tree's go.mod to a repo-relative directory.
//   - a path containing ".." - relative to the mock's own directory,
//     normalized by filepath.Join (which cleans the result), or an
//     unresolved mock is left unanchored.
//   - anything else - a bare filename in the mock's own directory.
func resolveMockSource(snap entities.Snapshot, mockDir, sourceLine string) (mockTarget, error) {
	path, ok := importPathSource(sourceLine)
	if !ok {
		return mockTarget{file: filepath.Join(mockDir, sourceLine)}, nil
	}

	dir, found, err := repoDirForImport(snap, path)
	if err != nil {
		return mockTarget{}, err
	}

	if !found {
		return mockTarget{}, nil
	}

	return mockTarget{dir: dir}, nil
}

func importPathSource(sourceLine string) (string, bool) {
	path, _, ok := strings.Cut(sourceLine, " (interfaces:")

	return strings.TrimSpace(path), ok
}

// repoDirForImport resolves an import path to a repo-relative directory
// using the module path declared in the target tree's own go.mod. An import
// outside that module names a dependency this run cannot anchor to.
func repoDirForImport(snap entities.Snapshot, importPath string) (string, bool, error) {
	modPath, err := modulePath(snap)
	if err != nil {
		return "", false, err
	}

	if modPath == "" {
		return "", false, nil
	}

	if importPath == modPath {
		return ".", true, nil
	}

	rel, ok := strings.CutPrefix(importPath, modPath+"/")

	return rel, ok, nil
}

// modulePath reads the target tree's own go.mod, since resolving an
// import-path mock header needs the module the tree was actually built as, not
// this tool's own. A tree with no go.mod at its root has no module path to
// resolve against, which is a legitimate shape, not a failure.
func modulePath(snap entities.Snapshot) (string, error) {
	data, err := os.ReadFile(filepath.Join(snap.Root, "go.mod"))
	if errors.Is(err, os.ErrNotExist) {
		return "", nil
	}

	if err != nil {
		return "", fmt.Errorf("read go.mod: %w", err)
	}

	for line := range strings.Lines(string(data)) {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(line), "module "); ok {
			return strings.TrimSpace(rest), nil
		}
	}

	return "", nil
}

func mockCandidates(byFile map[string][]entities.Decl, target mockTarget) []entities.Decl {
	if target.file != "" {
		return byFile[target.file]
	}

	var out []entities.Decl

	for file, decls := range byFile {
		if filepath.Dir(file) == target.dir {
			out = append(out, decls...)
		}
	}

	return out
}

// mockSubjectName recovers the interface name mockgen's generated identifier
// mirrors: MockFoo and NewMockFoo mirror Foo, and so does the
// MockFooMockRecorder type mockgen pairs with it.
func mockSubjectName(key entities.DeclKey) (string, bool) {
	name := key.Name
	if key.Kind == entities.KindMethod {
		recv, _, ok := strings.Cut(name, ".")
		if !ok {
			return "", false
		}

		name = recv
	}

	name = strings.TrimSuffix(name, "MockRecorder")

	if rest, ok := strings.CutPrefix(name, "NewMock"); ok {
		return rest, rest != ""
	}

	if rest, ok := strings.CutPrefix(name, "Mock"); ok {
		return rest, rest != ""
	}

	return "", false
}

func (mockgenRule) Anchors(
	context.Context,
	entities.Snapshot,
	[]entities.Decl,
) ([]entities.Anchor, error) {
	return nil, nil
}

// mockDependent is what waits for a mirrored interface, and which interfaces
// it mirrors.
type mockDependent struct {
	key      entities.DeclKey
	subjects []string
}

// mockDependents reports what to hang the mirror edges off.
//
// A GENERATED mock is one declaration standing for the whole file, so every
// interface it mirrors is a wait on that single declaration, and the names
// come from the source rather than from declaration names that no longer
// exist. A hand-written one is still cut per declaration, and each Mock type
// waits for its own subject.
func mockDependents(decls []entities.Decl, source []byte) []mockDependent {
	for _, decl := range decls {
		if decl.Key.Kind != entities.KindOther || decl.Key.Name != fileDeclName {
			continue
		}

		return []mockDependent{{key: decl.Key, subjects: mockedNamesIn(source)}}
	}

	out := make([]mockDependent, 0, len(decls))

	for _, decl := range decls {
		if name, named := mockSubjectName(decl.Key); named {
			out = append(out, mockDependent{key: decl.Key, subjects: []string{name}})
		}
	}

	return out
}
