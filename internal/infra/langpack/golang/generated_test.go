package golang

import (
	"testing"

	"github.com/wrapped-owls/redigit/internal/domain/entities"
)

func TestIsGenerated(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name   string
		source string
		want   bool
	}{
		{
			name:   "the marker mockgen writes",
			source: "// Code generated by MockGen. DO NOT EDIT.\npackage store\n",
			want:   true,
		},
		{
			name:   "the marker after a build tag",
			source: "//go:build integration\n\n// Code generated by goverter. DO NOT EDIT.\npackage a\n",
			want:   true,
		},
		{
			// A repository that hand-rolls small mocks has files named
			// _mock_test.go that a person wrote, and those SHOULD be cut by
			// declaration. On a real tree the marker split 228 generated
			// files from 5 hand-written ones with the same suffix.
			name:   "a hand-written mock",
			source: "package flow\n\ntype storeMock struct{}\n",
			want:   false,
		},
		{
			name:   "the phrase in prose, not as the marker line",
			source: "package a\n\n// This is Code generated by hand, DO NOT EDIT it lightly\n",
			want:   false,
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			if got := isGenerated([]byte(testCase.source)); got != testCase.want {
				t.Fatalf("isGenerated() = %v, want %v", got, testCase.want)
			}
		})
	}
}

// A generated file is written by its generator in ONE pass, so it must be one
// declaration. Cutting it by declaration produces a mock file holding
// NewMockX without the MockX it returns: on a real repository 100 of 235
// generated files were born in pieces, and 98 of those compiled while broken.
func TestDeclarationsKeepAGeneratedFileWhole(t *testing.T) {
	t.Parallel()

	source := []byte("// Code generated by MockGen. DO NOT EDIT.\n" +
		"package store\n\n" +
		"type MockReader struct{}\n\n" +
		"type MockReaderMockRecorder struct{}\n\n" +
		"func NewMockReader() *MockReader { return &MockReader{} }\n")

	decls, err := NewSyntax().Declarations(t.Context(), "store/reader_mock_test.go", source)
	if err != nil {
		t.Fatalf("Declarations() = %v", err)
	}

	if len(decls) != 1 {
		names := make([]string, 0, len(decls))
		for _, decl := range decls {
			names = append(names, decl.Key.Name)
		}

		t.Fatalf("a generated file became %d declarations (%v), want 1", len(decls), names)
	}

	if decls[0].Key.Name != fileDeclName {
		t.Fatalf("the declaration is %q, want %q", decls[0].Key.Name, fileDeclName)
	}

	if decls[0].Span.End != len(source) {
		t.Fatalf("the declaration spans %d of %d bytes", decls[0].Span.End, len(source))
	}
}

// The same file written by a person is still cut by declaration: a hand-rolled
// mock is code somebody maintains, and it grows a declaration at a time.
func TestDeclarationsStillCutAHandWrittenFile(t *testing.T) {
	t.Parallel()

	source := []byte("package flow\n\ntype storeMock struct{}\n\nfunc (storeMock) Read() error { return nil }\n")

	decls, err := NewSyntax().Declarations(t.Context(), "flow/store_mock_test.go", source)
	if err != nil {
		t.Fatalf("Declarations() = %v", err)
	}

	if len(decls) != 2 {
		t.Fatalf("a hand-written file became %d declarations, want 2", len(decls))
	}
}

// Rendering the one declaration of a generated file must reproduce it byte for
// byte: there is nothing to filter, and filtering through the printer would
// drop the marker comment that says it is generated.
func TestRenderReproducesAGeneratedFile(t *testing.T) {
	t.Parallel()

	source := []byte("// Code generated by MockGen. DO NOT EDIT.\n" +
		"package store\n\ntype MockReader struct{}\n")

	decls, err := NewSyntax().Declarations(t.Context(), "store/reader_mock_test.go", source)
	if err != nil {
		t.Fatalf("Declarations() = %v", err)
	}

	got, err := NewSyntax().Render(t.Context(), source, []entities.DeclKey{decls[0].Key})
	if err != nil {
		t.Fatalf("Render() = %v", err)
	}

	if string(got) != string(source) {
		t.Fatalf("Render() =\n%q\nwant\n%q", got, source)
	}
}
