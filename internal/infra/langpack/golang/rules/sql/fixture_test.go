const sqlcHeader = "// Code generated by sqlc. DO NOT EDIT.\n\npackage dbgen\n\n"

func schemaTree(t *testing.T) (entities.Snapshot, []entities.Decl) {
	t.Helper()

	root := t.TempDir()
	files := map[string]string{
		"database/entschema/go.mod":      "module example.com/entschema\n\ngo 1.26\n",
		"database/entschema/account.go":  entFile("Account", "Fields", "customixins.UUID()"),
		"database/entschema/template.go": entFile("Template", "Edges", "_ = Account.Type"),
		"database/entschema/owner.go": "package entschema\n\ntype OwnerMixin struct{}\n\n" +
			"func (OwnerMixin) Edges() { _ = Template.Type }\n",
		"database/entschema/customixins/uuid.go": "package customixins\n\nfunc UUID() {}\n",
		"database/migrations/0001_all.sql": "-- Create \"accounts\" table\nCREATE TABLE \"accounts\" (\"id\" uuid);\n" +
			"-- Create index \"account_id\" to table: \"accounts\"\nCREATE INDEX \"account_id\" ON \"accounts\" (\"id\");\n" +
			"-- Create \"templates\" table\nCREATE TABLE \"templates\" " +
			"(\"id\" uuid, \"account_id\" uuid, \"slug\" unaccent);\n" +
			"-- Modify \"templates\" table\nALTER TABLE \"templates\" ADD CONSTRAINT \"fk\" " +
			"FOREIGN KEY (\"account_id\") REFERENCES \"accounts\" (\"id\");\n" +
			"CREATE EXTENSION IF NOT EXISTS \"unaccent\";\n",
		"database/migrations/embed.go":  "package migrations\n\nvar FS int\n",
		"database/migrations/atlas.sum": "h1:x\n",
		"database/queries/account.sql":  "-- name: GetAccount :one\nSELECT id FROM accounts WHERE id = $1;\n",
		"database/queries/template.sql": "-- name: ListTemplates :many\n" +
			"SELECT unaccent(t.id) FROM templates t JOIN accounts a ON a.id = t.account_id;\n",
		"database/go.mod":    "module example.com/database\n\ngo 1.26\n",
		"database/sqlc.yaml": "version: \"2\"\n",
		"dbgen/db.go":        sqlcHeader + "type Queries struct{}\n",
		"dbgen/models.go":    sqlcHeader + "type Account struct{}\n\ntype Template struct{}\n",
		"dbgen/account.sql.go": sqlcHeader + "const GetAccount = `-- name: GetAccount :one`\n\n" +
			"func (q *Queries) GetAccount() (Account, error) { return Account{}, nil }\n",
		"dbgen/template.sql.go": sqlcHeader + "const ListTemplates = `-- name: ListTemplates :many`\n\n" +
			"type ListTemplatesRow struct{}\n\n" +
			"func (q *Queries) ListTemplates() ([]ListTemplatesRow, error) { return nil, nil }\n",
	}

	var decls []entities.Decl

	paths := make([]string, 0, len(files))

	for path, content := range files {
		testkit.WriteFile(t, root, path, content)
		paths = append(paths, path)

		found, err := declarationsOf(root, path)
		if err != nil {
			t.Fatalf("declarations of %s: %v", path, err)
		}

		decls = append(decls, found...)
	}

	return entities.Snapshot{Root: root, Files: paths}, decls
}

func declarationsOf(root, path string) ([]entities.Decl, error) {
	source, err := os.ReadFile(filepath.Join(root, path))
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}

	if filepath.Ext(path) == ".go" {
		return syntax.Declarations(context.Background(), path, source)
	}

	for _, chunker := range chunk.Registry {
		if chunker.Handles(path) {
			decls, err := chunker.Chunks(context.Background(), path, source)
			if err != nil {
				return nil, fmt.Errorf("chunk %s: %w", path, err)
			}

			return decls, nil
		}
	}

	return nil, nil
}

func entFile(typeName, method, body string) string {
	return "package entschema\n\ntype " + typeName + " struct{ ent.Schema }\n\nfunc (" +
		typeName + ") " + method + "() { " + body + " }\n"
}
