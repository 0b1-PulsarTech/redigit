type Mockgen struct{}

func (Mockgen) Name() string { return "mockgen" }

func (rule Mockgen) Edges(
	_ context.Context,
	snap entities.Snapshot,
	decls []entities.Decl,
) ([]entities.Edge, error) {
	byFile := declsource.GroupByFile(decls)

	var edges []entities.Edge

	for file, mockDecls := range byFile {
		source, err := declsource.ReadSource(snap, file)
		if err != nil {
			return nil, fmt.Errorf("mockgen source: %w", err)
		}

		sourceLine, ok := mockgenSourceLine(source)
		if !ok {
			continue
		}

		target, err := resolveMockSource(snap, filepath.Dir(file), sourceLine)
		if err != nil {
			return nil, err
		}

		if target == (mockTarget{}) {
			continue
		}

		candidates := mockCandidates(byFile, target)

		for _, dependent := range mockDependents(mockDecls, source) {
			for _, name := range dependent.subjects {
				if provider, found := declsource.FindTypeNamed(candidates, name); found {
					edges = append(edges, entities.Edge{
						Dependent: dependent.key,
						Provider:  provider,
						Reason:    entities.ReasonMirrors,
					})
				}
			}
		}
	}

	return edges, nil
}

func mockgenSourceLine(source []byte) (string, bool) {
	if !bytes.Contains(source, []byte("Code generated by MockGen")) {
		return "", false
	}

	scanner := bufio.NewScanner(bytes.NewReader(source))
	for scanner.Scan() {
		line := strings.TrimSpace(strings.TrimPrefix(scanner.Text(), "//"))
		if rest, ok := strings.CutPrefix(line, "Source:"); ok {
			return strings.TrimSpace(rest), true
		}
	}

	return "", false
}

type mockTarget struct {
	file string
	dir  string
}

func resolveMockSource(snap entities.Snapshot, mockDir, sourceLine string) (mockTarget, error) {
	path, ok := importPathSource(sourceLine)
	if !ok {
		return mockTarget{file: filepath.Join(mockDir, sourceLine)}, nil
	}

	dir, found, err := repoDirForImport(snap, path)
	if err != nil {
		return mockTarget{}, err
	}

	if !found {
		return mockTarget{}, nil
	}

	return mockTarget{dir: dir}, nil
}

func importPathSource(sourceLine string) (string, bool) {
	path, _, ok := strings.Cut(sourceLine, " (interfaces:")

	return strings.TrimSpace(path), ok
}

func repoDirForImport(snap entities.Snapshot, importPath string) (string, bool, error) {
	modPath, err := modulePath(snap)
	if err != nil {
		return "", false, err
	}

	if modPath == "" {
		return "", false, nil
	}

	if importPath == modPath {
		return ".", true, nil
	}

	rel, ok := strings.CutPrefix(importPath, modPath+"/")

	return rel, ok, nil
}

func modulePath(snap entities.Snapshot) (string, error) {
	data, err := os.ReadFile(filepath.Join(snap.Root, "go.mod"))
	if errors.Is(err, os.ErrNotExist) {
		return "", nil
	}

	if err != nil {
		return "", fmt.Errorf("read go.mod: %w", err)
	}

	for line := range strings.Lines(string(data)) {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(line), "module "); ok {
			return strings.TrimSpace(rest), nil
		}
	}

	return "", nil
}

func mockCandidates(byFile map[string][]entities.Decl, target mockTarget) []entities.Decl {
	if target.file != "" {
		return byFile[target.file]
	}

	var out []entities.Decl

	for file, decls := range byFile {
		if filepath.Dir(file) == target.dir {
			out = append(out, decls...)
		}
	}

	return out
}

func mockSubjectName(key entities.DeclKey) (string, bool) {
	name := key.Name
	if key.Kind == entities.KindMethod {
		recv, _, ok := strings.Cut(name, ".")
		if !ok {
			return "", false
		}

		name = recv
	}

	name = strings.TrimSuffix(name, "MockRecorder")

	if rest, ok := strings.CutPrefix(name, "NewMock"); ok {
		return rest, rest != ""
	}

	if rest, ok := strings.CutPrefix(name, "Mock"); ok {
		return rest, rest != ""
	}

	return "", false
}

func (Mockgen) Anchors(
	context.Context,
	entities.Snapshot,
	[]entities.Decl,
) ([]entities.Anchor, error) {
	return nil, nil
}

type mockDependent struct {
	key      entities.DeclKey
	subjects []string
}

func mockDependents(decls []entities.Decl, source []byte) []mockDependent {
	for _, decl := range decls {
		if decl.Key.Kind != entities.KindOther || decl.Key.Name != syntax.FileDeclName {
			continue
		}

		return []mockDependent{{key: decl.Key, subjects: mockedNamesIn(source)}}
	}

	out := make([]mockDependent, 0, len(decls))

	for _, decl := range decls {
		if name, named := mockSubjectName(decl.Key); named {
			out = append(out, mockDependent{key: decl.Key, subjects: []string{name}})
		}
	}

	return out
}
