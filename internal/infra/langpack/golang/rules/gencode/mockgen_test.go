const mockgenHeader = "// Code generated by MockGen. DO NOT EDIT.\n"

func TestMockgenRuleBareFilenameHeader(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	dir := "store"

	testkit.WriteFile(t, root, filepath.Join(dir, "reader.go"), `package store

type Reader interface {
	Read() error
}
`)
	testkit.WriteFile(
		t,
		root,
		filepath.Join(dir, "reader_mock_test.go"),
		mockgenHeader+`// Source: reader.go
package store

type MockReader struct{}

func (m *MockReader) Read() error { return nil }
`,
	)

	snap := entities.Snapshot{Root: root}

	decls := testkit.DeclareAll(t, root, []string{
		filepath.Join(dir, "reader.go"),
		filepath.Join(dir, "reader_mock_test.go"),
	})

	edges, err := Mockgen{}.Edges(context.Background(), snap, decls)
	if err != nil {
		t.Fatalf("Edges() error = %v", err)
	}

	assertMirrors(
		t,
		edges,
		entities.DeclKey{
			File: filepath.Join(dir, "reader.go"),
			Kind: entities.KindType,
			Name: "Reader",
		},
	)
}

