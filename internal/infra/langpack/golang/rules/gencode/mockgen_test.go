func TestMockgenRuleRecoversInterfaceNameFromIdentifiers(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name string
		key  entities.DeclKey
		want string
		ok   bool
	}{
		{
			"Mock prefix",
			entities.DeclKey{Kind: entities.KindType, Name: "MockReader"},
			"Reader",
			true,
		},
		{
			"NewMock constructor",
			entities.DeclKey{Kind: entities.KindFunc, Name: "NewMockReader"},
			"Reader",
			true,
		},
		{
			"MockRecorder suffix pairs with Mock prefix",
			entities.DeclKey{Kind: entities.KindType, Name: "MockReaderMockRecorder"},
			"Reader",
			true,
		},
		{
			"method keys off the receiver, not the method name",
			entities.DeclKey{Kind: entities.KindMethod, Name: "MockReader.Read"},
			"Reader",
			true,
		},
		{
			"unrelated name does not match",
			entities.DeclKey{Kind: entities.KindType, Name: "Reader"},
			"",
			false,
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			got, ok := mockSubjectName(testCase.key)
			if ok != testCase.ok || got != testCase.want {
				t.Fatalf(
					"mockSubjectName(%+v) = (%q, %v), want (%q, %v)",
					testCase.key,
					got,
					ok,
					testCase.want,
					testCase.ok,
				)
			}
		})
	}
}

func TestMockgenRuleNotAMockFile(t *testing.T) {
	t.Parallel()

	root := t.TempDir()

	testkit.WriteFile(t, root, "plain.go", `package sample

func Plain() {}
`)

	snap := entities.Snapshot{Root: root}

	decls := testkit.DeclareAll(t, root, []string{"plain.go"})

	edges, err := Mockgen{}.Edges(context.Background(), snap, decls)
	if err != nil {
		t.Fatalf("Edges() error = %v", err)
	}

	if len(edges) != 0 {
		t.Fatalf("got %d edges for a non-mock file, want 0", len(edges))
	}
}

func assertMirrors(t *testing.T, edges []entities.Edge, want entities.DeclKey) {
	t.Helper()

	for _, edge := range edges {
		if edge.Provider == want && edge.Reason == entities.ReasonMirrors {
			return
		}
	}

	t.Fatalf("no edge mirrors %+v; got %+v", want, edges)
}
