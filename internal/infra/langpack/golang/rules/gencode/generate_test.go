import (
	"os"
	"path/filepath"
	"testing"

	"github.com/wrapped-owls/redigit/internal/domain/entities"
	"github.com/wrapped-owls/redigit/internal/infra/langpack/golang/syntax"
)

func generateTree(t *testing.T, files map[string]string) entities.Snapshot {
	t.Helper()

	root := t.TempDir()
	paths := make([]string, 0, len(files))

	for name, body := range files {
		full := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			t.Fatal(err)
		}

		if err := os.WriteFile(full, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}

		paths = append(paths, name)
	}

	return entities.Snapshot{Root: root, Files: paths}
}

func TestGenerateDestinations(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name   string
		dir    string
		source string
		want   string
	}{
		{
			name:   "a destination beside the directive",
			dir:    "modules/wabapi/metaauth",
			source: "//go:generate go tool mockgen -source=$GOFILE -destination=repo_mock_test.go\n",
			want:   "modules/wabapi/metaauth/repo_mock_test.go",
		},
		{
			name:   "a destination in another directory",
			dir:    "a/b",
			source: "//go:generate mockgen -destination=../mocks/thing_mock.go\n",
			want:   "a/mocks/thing_mock.go",
		},
		{
			name:   "a directive with no destination",
			dir:    "a",
			source: "//go:generate stringer -type=Kind\n",
			want:   "",
		},
		{
			name:   "no directive at all",
			dir:    "a",
			source: "package a\n",
			want:   "",
		},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			got := generateDestinations(testCase.dir, []byte(testCase.source))

			if testCase.want == "" {
				if len(got) != 0 {
					t.Fatalf("generateDestinations() = %v, want none", got)
				}

				return
			}

			if len(got) != 1 || got[0] != testCase.want {
				t.Fatalf("generateDestinations() = %v, want [%s]", got, testCase.want)
			}
		})
	}
}

func TestGenerateRuleTiesAMockToItsDirective(t *testing.T) {
	t.Parallel()

	snap := generateTree(t, map[string]string{
		"store/repo.go": "package store\n\n" +
			"//go:generate mockgen -source=$GOFILE -destination=repo_mock_test.go\n\n" +
			"type Reader interface{ Read() error }\n",
		"store/repo_mock_test.go": "// Code generated by MockGen. DO NOT EDIT.\npackage store\n",
	})

	reader := entities.Decl{
		Key:  entities.DeclKey{File: "store/repo.go", Kind: entities.KindType, Name: "Reader"},
		Unit: "store",
		Span: entities.Span{Start: 10, End: 100},
	}
	mock := entities.Decl{
		Key: entities.DeclKey{
			File: "store/repo_mock_test.go", Kind: entities.KindOther, Name: syntax.FileDeclName,
		},
		Unit: "store",
		Span: entities.Span{Start: 0, End: 60},
	}

	edges, err := (Generate{}).Edges(t.Context(), snap, []entities.Decl{reader, mock})
	if err != nil {
		t.Fatalf("Edges() = %v", err)
	}

	found := false

	for _, edge := range edges {
		if edge.Dependent == mock.Key && edge.Provider == reader.Key {
			if edge.Reason != entities.ReasonGeneratedBy {
				t.Fatalf("reason = %q, want %q", edge.Reason, entities.ReasonGeneratedBy)
			}

			found = true
		}
	}

	if !found {
		t.Fatalf("the mock does not wait for the directive that writes it; got %v", edges)
	}
}

func TestGenerateRuleIgnoresAnAbsentDestination(t *testing.T) {
	t.Parallel()

	snap := generateTree(t, map[string]string{
		"a/reader.go": "package a\n\n//go:generate mockgen -destination=absent_mock_test.go\n",
	})

	reader := entities.Decl{
		Key:  entities.DeclKey{File: "a/reader.go", Kind: entities.KindType, Name: "Reader"},
		Unit: "a",
	}

	edges, err := (Generate{}).Edges(t.Context(), snap, []entities.Decl{reader})
	if err != nil {
		t.Fatalf("Edges() = %v", err)
	}

	if len(edges) != 0 {
		t.Fatalf("got %d edge(s) for a destination the tree does not hold", len(edges))
	}
}
