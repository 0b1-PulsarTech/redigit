func TestLineCount(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name string
		text string
		want int
	}{
		{"empty", "", 0},
		{"one terminated line", "a\n", 1},
		{"last line without newline", "a\nb", 2},
		{"blank lines count", "a\n\n\nb\n", 4},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			if got := lineCount([]byte(testCase.text)); got != testCase.want {
				t.Fatalf("lineCount(%q) = %d, want %d", testCase.text, got, testCase.want)
			}
		})
	}
}

func TestIsGenerated(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name   string
		file   string
		source string
		want   bool
	}{
		{
			"go marker",
			"db/q.sql.go",
			"// Code generated by sqlc. DO NOT EDIT.\n\npackage db\n",
			true,
		},
		{
			"go marker after a build tag",
			"a/gen.go",
			"//go:build x\n\n// Code generated by mockgen. DO NOT EDIT.\npackage a\n",
			true,
		},
		{
			"go marker after the package clause is prose",
			"a/a.go",
			"package a\n\n// Code generated by x. DO NOT EDIT.\n",
			false,
		},
		{"go file without marker", "a/a.go", "package a\n", false},
		{
			"marker without the ending is not the toolchain's",
			"a/a.go",
			"// Code generated by hand\npackage a\n",
			false,
		},
		{"go.sum by name", "mod/go.sum", "x v1 h1:abc\n", true},
		{"atlas.sum by name", "database/migrations/atlas.sum", "h1:abc\n", true},
		{
			"markdown that says so on line one",
			"docs/api.md",
			"# API reference (generated)\n\nbody\n",
			true,
		},
		{"markdown that does not", "docs/api.md", "# API reference\n\ngenerated later\n", false},
		{"empty file", "docs/empty.md", "", false},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			if got := IsGenerated(testCase.file, []byte(testCase.source)); got != testCase.want {
				t.Fatalf("IsGenerated(%q) = %v, want %v", testCase.file, got, testCase.want)
			}
		})
	}
}

func TestMeasure(t *testing.T) {
	t.Parallel()

	source := []byte(
		"// Code generated by x. DO NOT EDIT.\npackage a\n\nimport \"x\"\n\nfunc A() {\n}\n\nfunc B() {\n}\n",
	)
	first := bytes.Index(source, []byte("func A"))
	second := bytes.Index(source, []byte("func B"))

	decls := []entities.Decl{
		{Span: entities.Span{Start: second, End: len(source)}},
		{Span: entities.Span{Start: first, End: second - 1}},
		{Span: entities.Span{Start: 3, End: 99999}},
	}

	measure("a/a.go", source, decls)

	for index, want := range []struct{ lines, frame int }{{2, 5}, {3, 5}, {0, 0}} {
		if decls[index].Lines != want.lines || decls[index].Frame != want.frame {
			t.Fatalf("decl %d = %d lines, frame %d; want %d, %d",
				index, decls[index].Lines, decls[index].Frame, want.lines, want.frame)
		}
	}

	if !decls[0].Generated || !decls[1].Generated || decls[2].Generated {
		t.Fatalf(
			"generated = %v, %v, %v; want the span outside the file unmeasured",
			decls[0].Generated,
			decls[1].Generated,
			decls[2].Generated,
		)
	}
}
