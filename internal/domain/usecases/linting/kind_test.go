package linting

import "testing"

const (
	mockMarker = "// Code generated by MockGen. DO NOT EDIT.\n\npackage x\n"
	plainGo    = "package x\n"
)

func TestClassifyReadsTheMarkerOnTheBytes(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name   string
		path   string
		source string
		want   Kind
	}{
		{
			name:   "mock test with the marker",
			path:   "x_mock_test.go",
			source: mockMarker,
			want:   KindGenerated,
		},
		{
			name:   "mock test without the marker",
			path:   "x_mock_test.go",
			source: plainGo,
			want:   KindSource,
		},
		{
			name:   "pb.go with the marker",
			path:   "api/x.pb.go",
			source: "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n",
			want:   KindGenerated,
		},
		{name: "pb.go without a marker", path: "api/x.pb.go", source: plainGo, want: KindSource},
		{
			name:   "dart first line says generated",
			path:   "lib/a.g.dart",
			source: "// GENERATED CODE - DO NOT MODIFY BY HAND\n",
			want:   KindGenerated,
		},
		{name: "go.sum by name", path: "go.sum", source: "a h1:b\n", want: KindGenerated},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			got := Classify(testCase.path, []byte(testCase.source))
			if got != testCase.want {
				t.Fatalf("Classify(%q) = %d, want %d", testCase.path, got, testCase.want)
			}
		})
	}
}

