func TestIsBinary(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name   string
		source string
		want   bool
	}{
		{name: "text", source: "a\nb\n", want: false},
		{name: "empty", source: "", want: false},
		{name: "a NUL byte in the middle", source: "a\x00b", want: true},
		{name: "a NUL byte last", source: "ab\x00", want: true},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			t.Parallel()

			if got := IsBinary([]byte(testCase.source)); got != testCase.want {
				t.Fatalf("IsBinary(%q) = %v, want %v", testCase.source, got, testCase.want)
			}
		})
	}
}
